import { createServer, type Server } from 'node:http';
import type { AddressInfo } from 'node:net';
import { afterEach, describe, expect, it } from 'vitest';
import { OllamaClient, parseShow, resolveBaseUrl, type PullProgress } from './client';

describe('pull', () => {
  let server: Server | null = null;
  afterEach(() => server?.close());

  // an Ollama that answers /api/pull with these chunks, cut wherever the test cuts them
  async function ollamaSending(chunks: string[]): Promise<OllamaClient> {
    server = createServer(async (_req, res) => {
      res.writeHead(200, { 'content-type': 'application/x-ndjson' });
      for (const chunk of chunks) {
        res.write(chunk);
        await new Promise((r) => setTimeout(r, 5));
      }
      res.end();
    });
    await new Promise<void>((r) => server!.listen(0, '127.0.0.1', r));
    return new OllamaClient(`http://127.0.0.1:${(server.address() as AddressInfo).port}`);
  }

  it('reads progress lines split across chunks', async () => {
    const client = await ollamaSending([
      '{"status":"pulling manifest"}\n{"status":"pulling d8',
      '47","digest":"sha256:d847","total":100,"completed":40}\n',
      '{"status":"pulling d847","digest":"sha256:d847","total":100,"completed":100}\n{"status":"success"}',
    ]);
    const seen: PullProgress[] = [];
    await client.pull('m:q4', (p) => seen.push(p));
    expect(seen.map((p) => p.completed ?? p.status)).toEqual(['pulling manifest', 40, 100, 'success']);
  });

  it('fails with the error Ollama writes into the stream', async () => {
    const client = await ollamaSending(['{"status":"pulling manifest"}\n', '{"error":"pull model manifest: file does not exist"}\n']);
    await expect(client.pull('m:q4', () => {})).rejects.toThrow('pull model manifest: file does not exist');
  });

  it('fails when the stream ends before success', async () => {
    const client = await ollamaSending(['{"status":"pulling d847","digest":"sha256:d847","total":100,"completed":40}\n']);
    await expect(client.pull('m:q4', () => {})).rejects.toThrow('before it was complete');
  });
});

describe('resolveBaseUrl', () => {
  it.each([
    [undefined, 'http://127.0.0.1:11434'],
    ['', 'http://127.0.0.1:11434'],
    ['0.0.0.0', 'http://127.0.0.1:11434'],
    ['0.0.0.0:11500', 'http://127.0.0.1:11500'],
    [':11500', 'http://127.0.0.1:11500'],
    ['localhost:11434', 'http://localhost:11434'],
    ['http://gpu-box:8080', 'http://gpu-box:8080'],
    ['https://ollama.example', 'https://ollama.example'],
  ])('%s gives %s', (host, expected) => {
    expect(resolveBaseUrl(host)).toBe(expected);
  });
});

describe('parseShow', () => {
  it('finds a renderer only in the generated Modelfile', () => {
    const details = parseShow('m', {
      capabilities: ['completion', 'tools', 'thinking'],
      modelfile: 'FROM /blobs/sha256-x\nRENDERER qwen3.8\nPARSER qwen3.5\n',
      model_info: { 'qwen35.context_length': 262144, 'general.architecture': 'qwen35' },
    });
    expect(details).toEqual({
      name: 'm',
      capabilities: ['completion', 'tools', 'thinking'],
      hasRenderer: true,
      contextLength: 262144,
      architecture: 'qwen35',
      baseModel: null,
      basename: null,
    });
  });

  it('reads the base model a GGUF was made from as a Hugging Face repo id', () => {
    const details = parseShow('m', {
      model_info: {
        'general.basename': 'Qwen3.8-27B',
        'general.base_model.0.repo_url': 'https://huggingface.co/Qwen/Qwen3.8-27B',
      },
    });
    expect(details.baseModel).toBe('Qwen/Qwen3.8-27B');
    expect(details.basename).toBe('Qwen3.8-27B');
    expect(parseShow('m', { model_info: { 'general.base_model.0.repo_url': 'https://example.com/Qwen/Qwen3.8-27B' } }).baseModel).toBeNull();
  });

  it('reports a model without a renderer', () => {
    expect(parseShow('m', { modelfile: 'FROM /blobs/sha256-x\nTEMPLATE "{{ .Prompt }}"\n' }).hasRenderer).toBe(false);
  });
});

describe('blobs', () => {
  let server: Server | null = null;
  afterEach(() => server?.close());

  it('reads the weights and projector off the FROM lines of the Modelfile', async () => {
    const weights = 'd847e2c1e4aa276e4b7b8e9ad7628050e61e165d49ab995407bc36677a6f3864';
    const projector = '83ee4f4f205fa514161778c41df1ea14144faa0f713510893b63c2395f5c2d53';
    const modelfile = `# Modelfile generated by "ollama show"\nFROM D:\\ollama\\models\\blobs\\sha256-${weights}\nFROM /home/me/.ollama/models/blobs/sha256-${projector}\nTEMPLATE "{{ .Prompt }}"\nPARAMETER stop sha256-${'0'.repeat(64)}\n`;
    server = createServer((_req, res) => res.end(JSON.stringify({ modelfile })));
    await new Promise<void>((r) => server!.listen(0, '127.0.0.1', r));
    const client = new OllamaClient(`http://127.0.0.1:${(server.address() as AddressInfo).port}`);
    expect(await client.blobs('m:q4')).toEqual([weights, projector]);
  });
});
